def plot_series_with_mean(x, y, label):
    # Faint line
    line, = plt.plot(
        x, np.abs(y),
        linestyle='--',
        alpha=0.5
    )

    # Points
    plt.plot(
        x, np.abs(y),
        marker='o',
        linestyle='None',
        color=line.get_color(),
        label=label
    )

    # Mean line
    mean_val = np.mean(np.abs(y))
    plt.hlines(
        mean_val,
        x.min(),
        x.max(),
        colors=line.get_color(),
        linestyles='-'
    )

    return mean_val, line.get_color()

